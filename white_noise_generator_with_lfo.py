# --- APPLY LFO MODULATION FOR RAIN VOLUME ---
# Generate time vector
t = np.linspace(0., DURATION, T, endpoint=False)

# Generate LFO sine wave (ranges from 0 to 1)
raw_lfo = 0.5 * (np.sin(2 * np.pi * RAIN_LFO_FREQ * t) + 1.0)

# Scale LFO for modulation (e.g., if DEPTH=0.4, signal ranges from 0.6 to 1.0)
# This prevents the sound from going completely silent.
modulation_signal = (1.0 - RAIN_LFO_DEPTH) + (raw_lfo * RAIN_LFO_DEPTH)

# Apply modulation
rain_sound *= modulation_signal
# -------------------------------------------

# Mix (if you had other components, you would sum them here)
final_mix = rain_sound

# Normalize the final result using the function
final_audio_normalized = normalize_audio(final_mix)

print("White noise sound component (with LFO) generated.")

Audio(final_audio_normalized, rate=SAMPLE_RATE)